import { Router } from "express";
import { controller } from "./payments.controller.js";
import { validateZod } from "../../middleware/validateZod.js";
import { authenticate, requirePermission } from "../../middleware/auth.js";
import { createSchema, listSchema, refundSchema, verifySchema } from "./payments.schemas.js";
const router = Router();
router.post("/payments/token", authenticate("customer"), validateZod(createSchema), controller.create);
router.post("/payments/:paymentId/cancel", authenticate("customer"), controller.createPaymentsCancel);
router.get("/me/payments", authenticate("customer"), validateZod(listSchema), controller.mine);
router.get("/admin/payments", authenticate("admin"), requirePermission("sales.read"), validateZod(listSchema), controller.list);
router.patch("/admin/payments/:paymentId/verify", authenticate("admin"), requirePermission("sales.write"), validateZod(verifySchema), controller.updateAdminPaymentsVerify);
router.post("/admin/payments/:paymentId/refund", authenticate("admin"), requirePermission("sales.write"), validateZod(refundSchema), controller.recordVerifiedRefund);
export default router;
