import { Router } from "express";
import multer from "multer";
import { controller } from "./documents.controller.js";
import { validateZod } from "../../middleware/validateZod.js";
import { authenticate, requirePermission } from "../../middleware/auth.js";
import { createSchema, listSchema } from "./documents.schemas.js";
import { uploadLimiter } from "../../middleware/rateLimit.js";
import { service } from "./documents.service.js";
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 25 * 1024 * 1024 } });
const router = Router();
router.post("/documents/upload-intents", authenticate(), uploadLimiter, validateZod(createSchema), controller.createDocumentsUploadIntents);
router.post("/documents", authenticate(), uploadLimiter, upload.single("file"), controller.createDocuments);
router.get("/documents/:documentId/read-url", authenticate(), controller.getDocumentsReadUrl);
router.get("/admin/documents", authenticate("admin"), requirePermission("properties.read"), validateZod(listSchema), controller.list);
export default router;